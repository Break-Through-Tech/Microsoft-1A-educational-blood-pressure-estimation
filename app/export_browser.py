"""Export notebook features and the existing XGBoost trees for local browser inference."""
import ast
import gzip
import inspect
import json

from server import APP, Predictor, extract_inputs, load_feature_helpers

def main():
    destination = APP / "web" / "local-bp"
    destination.mkdir(exist_ok=True)
    predictor = Predictor()
    definition = ast.parse(inspect.getsource(load_feature_helpers)).body[0]
    wanted = ast.literal_eval(next(node.value for node in definition.body
        if isinstance(node, ast.Assign) and node.targets[0].id == "wanted"))
    notebook = json.loads((APP.parent / "notebooks/final.ipynb").read_text(encoding="utf-8"))
    sources = []
    for cell in notebook["cells"]:
        names = wanted.get(cell.get("id"), set())
        if not names:
            continue
        tree = ast.parse("".join(cell["source"]))
        for node in tree.body:
            keep = isinstance(node, ast.FunctionDef) and node.name in names
            if isinstance(node, ast.Assign):
                keep = any(isinstance(part, ast.Name) and part.id in names
                    for target in node.targets for part in ast.walk(target))
            if keep:
                sources.append(ast.unparse(node))
    header = """# Generated by app/export_browser.py from notebooks/final.ipynb.
import json
import numpy as np
import pandas as pd
from scipy.fft import rfft, rfftfreq
from scipy.signal import butter, filtfilt, find_peaks, welch, windows
from numpy.lib.stride_tricks import sliding_window_view
from itertools import combinations
from contextlib import nullcontext

# Browser scientific libraries run on the worker thread.
def threadpool_limits(limits=None):
    return nullcontext()
"""
    (destination / "features.py").write_text(header + "\n\n".join(sources) +
        "\n\n" + inspect.getsource(extract_inputs), encoding="utf-8")
    exported = {"columns": predictor.columns, "models": []}
    for estimator in predictor.models:
        learner = json.loads(estimator.get_booster().save_raw(raw_format="json"))["learner"]
        assert learner["objective"]["name"] == "reg:squarederror"
        count = int(learner["attributes"]["best_iteration"]) + 1
        model = learner["gradient_booster"]["model"]
        trees = []
        for tree in model["trees"][:count]:
            assert not any(tree["split_type"])
            trees.append({key: tree[key] for key in
                ["left_children", "right_children", "split_indices", "split_conditions"]})
        base = json.loads(learner["learner_model_param"]["base_score"])[0]
        exported["models"].append({"base": base, "trees": trees})
    (destination / "trees.json.gz").write_bytes(gzip.compress(json.dumps(exported,
        separators=(",", ":")).encode(), mtime=0))

if __name__ == "__main__":
    main()
